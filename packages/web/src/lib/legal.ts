/** Как продавец называется в текстах документов. */
export function sellerLine(): string {
  const name = req(LEGAL.operatorName);
  const inn = `ИНН ${req(LEGAL.inn)}`;
  if (LEGAL.status === 'ИП') {
    return `Индивидуальный предприниматель ${name}, ОГРНИП ${req(LEGAL.ogrnip)}, ${inn}`;
  }
  return `${name}, налогоплательщик налога на профессиональный доход (самозанятый), ${inn}`;
}

/** Подстановка в текст: пустой реквизит виден сразу. */
export function req(value: string): string {
  return value.trim() || '___';
}
